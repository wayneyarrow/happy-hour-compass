/**
 * scripts/buildGreaterSanDiegoCitiesSql.ts
 *
 * Generates the reviewed Step 2 geography SQL for Greater San Diego from the
 * single roster definition (src/lib/geo/rosters/greaterSanDiego.ts):
 *
 *   docs/operations/greater-san-diego/step2-cities-preflight.sql  (read-only)
 *   docs/operations/greater-san-diego/step2-cities-apply.sql      (writes — approval required)
 *   docs/operations/greater-san-diego/step2-cities-rollback.sql   (writes — approval required)
 *
 * This script never connects to a database; it only writes the three files.
 * Usage (from operator-admin/):  npx tsx scripts/buildGreaterSanDiegoCitiesSql.ts
 */

import * as fs from "fs";
import * as path from "path";
import { GREATER_SAN_DIEGO_CITIES, GREATER_SAN_DIEGO_MARKET_SLUG } from "../src/lib/geo/rosters/greaterSanDiego";

const OUT_DIR = path.resolve(__dirname, "../../docs/operations/greater-san-diego");
const MARKET = GREATER_SAN_DIEGO_MARKET_SLUG;
const SOLANA_BEACH_ID = "22ee8a97-ae30-4eb0-92ce-ca456cb5bbdd"; // Step 1 (apply.sql), default city
const ENCORE_ID = "4ecc0d2c-3ef0-4f85-8f34-5b4e079e1840";

const NEW_CITIES = GREATER_SAN_DIEGO_CITIES.filter((c) => !c.existing);
const NEW_SLUGS = NEW_CITIES.map((c) => c.slug);

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const num = (n: number | null) => (n === null ? "NULL" : String(n));
const slugList = `ARRAY[${NEW_SLUGS.map(q).join(", ")}]::text[]`;

const header = (title: string, body: string) =>
  `-- Greater San Diego Step 2 — ${title}\n` +
  `-- GENERATED by operator-admin/scripts/buildGreaterSanDiegoCitiesSql.ts from\n` +
  `-- src/lib/geo/rosters/greaterSanDiego.ts — edit the roster and regenerate; never hand-edit.\n` +
  body;

// ── Preflight (read-only) ─────────────────────────────────────────────────
const preflight = header(
  "PREFLIGHT (read-only, safe any time).",
  `--   supabase db query --linked -f docs/operations/greater-san-diego/step2-cities-preflight.sql
-- Expect: market active/US/CA; exactly 1 existing city (solana-beach, default, id ${SOLANA_BEACH_ID});
-- new_slugs_already_present = 0; Encore still published in solana-beach.

SELECT m.slug AS market, m.status, m.country, m.province, m.radius_km,
       dc.slug AS default_city,
       (SELECT count(*) FROM public.cities c WHERE c.market_id = m.id) AS existing_city_rows,
       (SELECT coalesce(json_agg(c.slug ORDER BY c.slug), '[]'::json) FROM public.cities c WHERE c.market_id = m.id) AS existing_city_slugs,
       (SELECT count(*) FROM public.cities c WHERE c.market_id = m.id AND c.slug = ANY(${slugList})) AS new_slugs_already_present,
       (SELECT count(*) FROM public.venues v WHERE v.market_id = m.id) AS venues_in_market,
       (SELECT json_build_object('city', vc.slug, 'is_published', v.is_published, 'slug', v.slug)
          FROM public.venues v LEFT JOIN public.cities vc ON vc.id = v.city_id
         WHERE v.id = '${ENCORE_ID}') AS encore
  FROM public.markets m
  LEFT JOIN public.cities dc ON dc.id = m.default_city_id
 WHERE m.slug = '${MARKET}';

-- Unassigned venues whose city text would resolve to a new city once applied
-- (informational; this step never assigns them).
SELECT v.id, v.name, v.city, v.region, v.is_published, v.source
  FROM public.venues v
 WHERE v.market_id IS NULL
   AND (v.region ILIKE 'ca' OR v.region ILIKE 'california');
`
);

// ── Apply (writes) ─────────────────────────────────────────────────────────
const values = NEW_CITIES.map(
  (c, i) =>
    `    (${q(c.slug)}, ${q(c.name)}, ${i + 2}, ${num(c.center_lat)}, ${num(c.center_lng)})`
).join(",\n");

const apply = header(
  "APPLY. Writes to the SHARED database (staging AND Production).",
  `-- Run ONLY after Wayne's explicit approval, after step2-cities-preflight.sql shows the expected state:
--   supabase db query --linked -f docs/operations/greater-san-diego/step2-cities-apply.sql
-- One transaction. Inserts ${NEW_CITIES.length} cities into Greater San Diego (status active,
-- supports_neighbourhoods false). Every guard RAISEs (rolling back everything) unless the
-- market and Solana Beach are exactly as Step 1 left them and none of the new slugs exist.
-- Touches no market row (default city stays solana-beach), no existing city, no venue
-- (Encore Sushi untouched), no other market.
-- Centers: US Census 2024 Gazetteer internal points (public domain); NULL where the
-- Gazetteer has no place record. display_order follows the roster (Solana Beach keeps 1).
BEGIN;

DO $$
DECLARE n integer; m_id uuid;
BEGIN
  SELECT id INTO m_id FROM public.markets
   WHERE slug = '${MARKET}' AND status = 'active' AND country = 'US' AND province = 'CA';
  IF m_id IS NULL THEN RAISE EXCEPTION 'greater-san-diego market missing or changed — nothing applied'; END IF;

  IF NOT EXISTS (SELECT 1 FROM public.markets WHERE id = m_id AND default_city_id = '${SOLANA_BEACH_ID}') THEN
    RAISE EXCEPTION 'default city is no longer solana-beach — nothing applied';
  END IF;

  SELECT count(*) INTO n FROM public.cities WHERE market_id = m_id;
  IF n <> 1 THEN RAISE EXCEPTION 'expected exactly 1 existing city (solana-beach), found % — nothing applied', n; END IF;

  SELECT count(*) INTO n FROM public.cities WHERE market_id = m_id AND slug = ANY(${slugList});
  IF n <> 0 THEN RAISE EXCEPTION '% new city slug(s) already exist — nothing applied', n; END IF;

  INSERT INTO public.cities (market_id, slug, name, status, supports_neighbourhoods, display_order, center_lat, center_lng)
  SELECT m_id, v.slug, v.name, 'active', false, v.display_order, v.center_lat, v.center_lng
    FROM (VALUES
${values}
    ) AS v(slug, name, display_order, center_lat, center_lng);
  GET DIAGNOSTICS n = ROW_COUNT;
  IF n <> ${NEW_CITIES.length} THEN RAISE EXCEPTION 'expected ${NEW_CITIES.length} cities inserted, got %', n; END IF;

  SELECT count(*) INTO n FROM public.cities WHERE market_id = m_id;
  IF n <> ${NEW_CITIES.length + 1} THEN RAISE EXCEPTION 'expected ${NEW_CITIES.length + 1} cities in market, found %', n; END IF;
END $$;

-- Verification (printed by the CLI): ${NEW_CITIES.length + 1} active cities, default still solana-beach,
-- Encore still in solana-beach and unchanged.
SELECT m.slug AS market, dc.slug AS default_city,
       count(c.*) AS cities, count(c.*) FILTER (WHERE c.status = 'active') AS active_cities,
       (SELECT vc.slug FROM public.venues v JOIN public.cities vc ON vc.id = v.city_id WHERE v.id = '${ENCORE_ID}') AS encore_city
  FROM public.markets m
  JOIN public.cities c ON c.market_id = m.id
  LEFT JOIN public.cities dc ON dc.id = m.default_city_id
 WHERE m.slug = '${MARKET}'
 GROUP BY m.slug, dc.slug;

COMMIT;
`
);

// ── Rollback (writes) ──────────────────────────────────────────────────────
const rollback = header(
  "ROLLBACK. Writes to the SHARED database (staging AND Production).",
  `-- Removes ONLY the Step 2 cities, and refuses (RAISE, nothing deleted) while anything references
-- one of them: a venue, neighbourhood, collection, homepage, content guide, or a market default.
-- Never touches solana-beach (Step 1) or Encore Sushi. Run only with Wayne's explicit approval.
--   supabase db query --linked -f docs/operations/greater-san-diego/step2-cities-rollback.sql
BEGIN;

DO $$
DECLARE n integer; m_id uuid; ids uuid[];
BEGIN
  SELECT id INTO m_id FROM public.markets WHERE slug = '${MARKET}';
  IF m_id IS NULL THEN RAISE EXCEPTION 'greater-san-diego market missing'; END IF;

  SELECT array_agg(id) INTO ids FROM public.cities WHERE market_id = m_id AND slug = ANY(${slugList});
  IF ids IS NULL THEN RAISE NOTICE 'no Step 2 cities present — nothing to do'; RETURN; END IF;

  SELECT count(*) INTO n FROM public.venues WHERE city_id = ANY(ids);
  IF n > 0 THEN RAISE EXCEPTION '% venue(s) still assigned to a Step 2 city — reassign or remove them first', n; END IF;
  SELECT count(*) INTO n FROM public.neighbourhoods WHERE city_id = ANY(ids);
  IF n > 0 THEN RAISE EXCEPTION '% neighbourhood(s) reference a Step 2 city', n; END IF;
  SELECT count(*) INTO n FROM public.collections WHERE city_id = ANY(ids);
  IF n > 0 THEN RAISE EXCEPTION '% collection(s) reference a Step 2 city', n; END IF;
  SELECT count(*) INTO n FROM public.homepages WHERE city_id = ANY(ids);
  IF n > 0 THEN RAISE EXCEPTION '% homepage(s) reference a Step 2 city', n; END IF;
  SELECT count(*) INTO n FROM public.content_guides WHERE city_id = ANY(ids);
  IF n > 0 THEN RAISE EXCEPTION '% content guide(s) reference a Step 2 city', n; END IF;
  SELECT count(*) INTO n FROM public.markets WHERE default_city_id = ANY(ids);
  IF n > 0 THEN RAISE EXCEPTION 'a market default city is a Step 2 city — reset it first'; END IF;

  DELETE FROM public.cities WHERE id = ANY(ids);
  GET DIAGNOSTICS n = ROW_COUNT;
  IF n <> array_length(ids, 1) THEN RAISE EXCEPTION 'expected % deleted, got %', array_length(ids, 1), n; END IF;
  IF NOT EXISTS (SELECT 1 FROM public.cities WHERE id = '${SOLANA_BEACH_ID}') THEN
    RAISE EXCEPTION 'solana-beach missing after rollback — aborting';
  END IF;
END $$;

SELECT c.slug FROM public.cities c JOIN public.markets m ON m.id = c.market_id WHERE m.slug = '${MARKET}';

COMMIT;
`
);

fs.writeFileSync(path.join(OUT_DIR, "step2-cities-preflight.sql"), preflight);
fs.writeFileSync(path.join(OUT_DIR, "step2-cities-apply.sql"), apply);
fs.writeFileSync(path.join(OUT_DIR, "step2-cities-rollback.sql"), rollback);
console.log(`Wrote step2-cities-{preflight,apply,rollback}.sql — ${NEW_CITIES.length} new cities (+ solana-beach existing).`);
